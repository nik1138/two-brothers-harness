/**
 * Session rewind — drop the last N operator turns from a persisted session.
 *
 * A session JSONL is an append-only log of protocol envelopes. Rewinding is
 * the operator's "undo the last task": remove the last N operator-task
 * boundaries (each user task envelope plus every brother envelope produced for
 * it) so the operator can retype a better task without a growing context or a
 * new session. This module is the pure, testable core; an HTTP route / CLI
 * action can call {@link rewindSession} later (no server wiring lives here).
 *
 * ## What is an operator turn?
 *
 * An operator turn starts at a `user -> senior` `message` envelope whose
 * payload text is a real operator task. Several envelopes share that exact
 * shape but are generated by the harness or by the app around a task, so the
 * boundary rule excludes each one explicitly:
 *
 * - compaction summaries — `isCompactionSummary` (`COMPACTION_SUMMARY_PREFIX`);
 * - structured-payload repair requests — `[[REPAIR_REQUEST]]`…`[[/REPAIR_REQUEST]]`
 *   (`payloads.ts::REPAIR_REQUEST_PREFIX`; a repair turn belongs to the task
 *   that already started, not to a new one);
 * - mid-run operator steering — `harness.ts::STEERING_PREFIX`;
 * - attached-context blocks injected *before* a task by the server/TUI
 *   `@skill:` / `@file` mentions — the `<skill-loaded …>` and `<file …>` opening
 *   tags `mentions.ts::renderSkillLoadedBlock` / `renderFileBlock` render (a
 *   model-requested skill body uses the same `<skill-loaded>` tag, but it is
 *   appended inside its own turn, never as a task).
 *
 * A message addressed to anyone other than the senior is never a task
 * boundary, and a blank payload text is not a task. The marker rule is the
 * only honest discriminator available in the envelope log; an operator task
 * whose literal text begins with one of the reserved markers would be
 * classified as generated context (the same reserved-marker ambiguity exists
 * in the rendered transcript). Everything else is a real task.
 *
 * ## Cut semantics
 *
 * The last `turns` operator turns are removed, clamped to the number of
 * rewindable turns (the caller validates `1..100` with
 * {@link validateRewindTurns}; the pure helper additionally clamps to what the
 * session actually holds). The cut never crosses a compaction summary: the
 * summary (and everything before it) always stays in the kept prefix, and a
 * request deeper than the turns after the summary is clamped honestly with
 * `stoppedAtCompaction: true`. A continuation attachment block immediately
 * preceding the earliest removed task is removed with that task (it was
 * attached for it), mirroring kimi-code's prompt-injection absorption.
 *
 * The kept prefix preserves the original envelopes — and therefore their dense
 * `seq` numbering — byte for byte; nothing is renumbered here. Callers rewrite
 * through `SessionStore.rewrite()` (temp file + rename), so the persisted file
 * keeps the session invariant "dense seq, one envelope per line" as a
 * consequence of removing a *suffix* of a dense log. Malformed but parseable
 * records are tolerated by the pure helpers (they are simply not turn
 * boundaries); a torn/corrupt JSONL line surfaces through
 * `SessionStore.loadStrict()` as `SessionError` before anything is rewritten.
 * (Read/resume paths recover a torn FINAL fragment instead; a destructive
 * rewind deliberately stays strict so it never rewrites on a partial read.)
 *
 * ## Provenance
 *
 * Adapted design, no code copied (references are MIT, `research/vendor/`
 * only): kimi-code `packages/agent-core-v2/src/agent/contextMemory/contextOps.ts`
 * (`computeUndoCut` / `precheckUndo`: scan backwards over turn anchors, absorb
 * prompt-owned injections, stop at a compaction boundary) and
 * `.../agent/undo/undoService.ts` (availability/precheck vocabulary), plus
 * opencode `packages/core/src/session/revert.ts` (cut at a message boundary).
 * Here the anchors and markers are the Two Brothers protocol envelopes.
 */
import { isCompactionSummary } from "./compaction.ts";
import { STEERING_PREFIX } from "./harness.ts";
import { REPAIR_REQUEST_PREFIX } from "./payloads.ts";
import type { Message } from "./protocol.ts";
import { SessionError, type SessionStore } from "./session.ts";

/** Smallest accepted rewind depth. */
export const MIN_REWIND_TURNS = 1;

/** Largest accepted rewind depth (a session is not a database). */
export const MAX_REWIND_TURNS = 100;

/** Opening tag of an attached skill block (`mentions.ts` renderer). */
const ATTACHED_SKILL_TAG = "<skill-loaded";

/** Opening tag of an attached file block (`mentions.ts` renderer). */
const ATTACHED_FILE_TAG = "<file ";

/** One operator task boundary in the envelope log. */
export interface OperatorTurn {
  /** 0-based index of the task envelope in the events array. */
  index: number;
  /** The operator task text (payload.text), exactly as persisted. */
  text: string;
}

/** Result of {@link validateRewindTurns}. */
export type RewindTurnsParse = { ok: true; turns: number } | { ok: false; error: string };

/**
 * The boundary that determined the cut: the requested turn depth
 * (`operator-turn`), a compaction summary the cut may not cross
 * (`compaction-summary`), or the start of the session (`session-start`).
 */
export type RewindStop = "operator-turn" | "compaction-summary" | "session-start";

/** Result of {@link computeRewindCut}: keep `events[0..cutIndex)`, drop the rest. */
export interface RewindCut {
  /** Index of the first kept event (`0..events.length`). */
  cutIndex: number;
  /** Events kept (`cutIndex`). */
  keptCount: number;
  /** Events removed (`events.length - cutIndex`). */
  removedCount: number;
  /** Operator turns actually removed (the clamped depth). */
  turns: number;
  /** The depth the caller asked for, before clamping. */
  requestedTurns: number;
  /** True when the compaction boundary, not the turn depth, limited the cut. */
  stoppedAtCompaction: boolean;
  /** Which boundary determined the cut (see {@link RewindStop}). */
  stopsBefore: RewindStop;
  /** One honest, bounded human sentence describing the outcome. */
  reason: string;
}

/** Result of {@link rewindSession}. */
export interface RewindSessionResult {
  cut: RewindCut;
  /** True when the store was rewritten; false when the cut removed nothing. */
  rewritten: boolean;
  /** The session file path (for the later route/CLI message). */
  path: string;
}

function asRecord(value: unknown): Record<string, unknown> | null {
  if (typeof value !== "object" || value === null || Array.isArray(value)) return null;
  return value as Record<string, unknown>;
}

/**
 * Payload text of a `user -> senior` `message` envelope, or null when the
 * record is not shaped like one. Deliberately tolerant: a malformed record is
 * simply "not a task boundary", never a throw.
 */
function userEnvelopeText(event: unknown): string | null {
  const record = asRecord(event);
  if (record === null) return null;
  if (record.from !== "user" || record.kind !== "message") return null;
  const payload = asRecord(record.payload);
  if (payload === null) return null;
  return typeof payload.text === "string" ? payload.text : null;
}

/** True for a real operator task envelope (the turn-boundary rule above). */
function isRealOperatorTask(event: unknown): boolean {
  const record = asRecord(event);
  const text = userEnvelopeText(event);
  if (record === null || text === null) return false;
  // Operator tasks are always addressed to the senior; anything else (a
  // harness repair/skill envelope addressed to the junior, say) is not a turn.
  if (record.to !== "senior") return false;
  if (text.trim() === "") return false;
  if (isCompactionSummary(event as Message)) return false;
  if (text.startsWith(REPAIR_REQUEST_PREFIX)) return false;
  if (text.startsWith(STEERING_PREFIX)) return false;
  if (text.startsWith(ATTACHED_SKILL_TAG) || text.startsWith(ATTACHED_FILE_TAG)) return false;
  return true;
}

/**
 * True for an attached-context block the server/TUI appends before a task
 * (`@skill:` / `@file` mentions). Used to absorb those blocks into the task
 * they were attached for when that task is removed.
 */
function isAttachedContextEnvelope(event: unknown): boolean {
  const record = asRecord(event);
  const text = userEnvelopeText(event);
  if (record === null || text === null || record.to !== "senior") return false;
  return text.startsWith(ATTACHED_SKILL_TAG) || text.startsWith(ATTACHED_FILE_TAG);
}

/** Index of the last compaction-summary envelope, or -1 when there is none. */
function lastCompactionSummaryIndex(events: readonly Message[]): number {
  for (let index = events.length - 1; index >= 0; index -= 1) {
    const event = events[index];
    if (event !== undefined && isCompactionSummary(event)) return index;
  }
  return -1;
}

/** Every real operator task in the envelope log, in file order. */
export function findOperatorTurns(events: readonly Message[]): OperatorTurn[] {
  const turns: OperatorTurn[] = [];
  for (let index = 0; index < events.length; index += 1) {
    const event = events[index];
    if (event === undefined || !isRealOperatorTask(event)) continue;
    turns.push({ index, text: String((event as Message).payload.text) });
  }
  return turns;
}

/** Validate one rewind depth from an untrusted boundary (HTTP body/CLI arg). */
export function validateRewindTurns(value: unknown): RewindTurnsParse {
  if (typeof value !== "number" || !Number.isInteger(value)) {
    return {
      ok: false,
      error: `rewind turns must be an integer between ${MIN_REWIND_TURNS} and ${MAX_REWIND_TURNS}`,
    };
  }
  if (value < MIN_REWIND_TURNS || value > MAX_REWIND_TURNS) {
    return {
      ok: false,
      error: `rewind turns must be between ${MIN_REWIND_TURNS} and ${MAX_REWIND_TURNS}`,
    };
  }
  return { ok: true, turns: value };
}

/** Build the no-op cut (nothing removed; `cutIndex` points past the log). */
function noopCut(
  events: readonly Message[],
  turns: number,
  reason: string,
  boundary: { stoppedAtCompaction: boolean; stopsBefore: RewindStop },
): RewindCut {
  return {
    cutIndex: events.length,
    keptCount: events.length,
    removedCount: 0,
    turns: 0,
    requestedTurns: Number.isFinite(turns) ? Math.floor(turns) : 0,
    stoppedAtCompaction: boundary.stoppedAtCompaction,
    stopsBefore: boundary.stopsBefore,
    reason,
  };
}

/**
 * Compute the cut that removes the last `turns` operator turns.
 *
 * Pure: the input array is never mutated. `turns` may be any positive integer
 * (it is clamped to what the session holds); an invalid depth is a no-op with
 * an honest reason rather than a throw, so callers can always render the
 * result. Boundary callers should validate first with
 * {@link validateRewindTurns}.
 */
export function computeRewindCut(events: readonly Message[], turns: number): RewindCut {
  if (!Number.isInteger(turns) || turns < MIN_REWIND_TURNS) {
    return noopCut(events, turns, "rewind needs a positive whole number of turns", {
      stoppedAtCompaction: false,
      stopsBefore: "session-start",
    });
  }
  const operatorTurns = findOperatorTurns(events);
  if (operatorTurns.length === 0) {
    return noopCut(events, turns, "the session has no operator turns to rewind", {
      stoppedAtCompaction: false,
      stopsBefore: "session-start",
    });
  }
  // A compaction summary is a hard floor: everything before it (including
  // turns folded into it) is already summarized and must stay in the kept
  // prefix, or a resumed context would lose the task that the summary
  // describes and the summary would reference envelopes that no longer exist.
  const summaryIndex = lastCompactionSummaryIndex(events);
  const rewindable =
    summaryIndex < 0 ? operatorTurns : operatorTurns.filter((turn) => turn.index > summaryIndex);
  if (rewindable.length === 0) {
    return noopCut(
      events,
      turns,
      "the only operator turns are covered by a compaction summary; nothing can be rewound",
      { stoppedAtCompaction: true, stopsBefore: "compaction-summary" },
    );
  }

  const depth = Math.min(turns, rewindable.length);
  const target = rewindable[rewindable.length - depth];
  if (target === undefined) {
    // Unreachable (depth >= 1 and rewindable is non-empty); keeps the types
    // honest without inventing a partial state.
    return noopCut(events, turns, "the session has no rewindable operator turns", {
      stoppedAtCompaction: false,
      stopsBefore: "session-start",
    });
  }
  let cutIndex = target.index;
  // Attached-context blocks belong to the task that follows them (the
  // server/TUI mention injection order): remove them with that task instead of
  // leaving stale file/skill context in front of the retyped task.
  while (cutIndex > 0 && isAttachedContextEnvelope(events[cutIndex - 1])) cutIndex -= 1;
  // Defensive floor: the summary itself never leaves the kept prefix.
  if (summaryIndex >= 0 && cutIndex <= summaryIndex) cutIndex = summaryIndex + 1;

  const keptCount = cutIndex;
  const removedCount = events.length - cutIndex;
  const clampedByCompaction = summaryIndex >= 0 && turns > rewindable.length;
  const clampedByStart = summaryIndex < 0 && turns > rewindable.length;
  const stopsBefore: RewindStop = clampedByCompaction
    ? "compaction-summary"
    : clampedByStart
      ? "session-start"
      : "operator-turn";
  const reason = clampedByCompaction
    ? `removed ${depth} operator turn(s); the requested ${turns} would cross a compaction summary, ` +
      `so the summary and everything before it are kept`
    : clampedByStart
      ? `removed all ${depth} operator turn(s); the session start is the boundary ` +
        `(requested ${turns})`
      : `removed the last ${depth} operator turn(s) (${removedCount} envelope(s)); ` +
        `${keptCount} envelope(s) kept`;
  return {
    cutIndex,
    keptCount,
    removedCount,
    turns: depth,
    requestedTurns: turns,
    stoppedAtCompaction: clampedByCompaction,
    stopsBefore,
    reason,
  };
}

/**
 * Rewind one persisted session: load → compute → rewrite the kept prefix.
 *
 * Errors are consistent with `SessionStore`/`SessionError`: an invalid depth,
 * a torn/corrupt session file (through the strict read) and a failed rewrite
 * all throw `SessionError` before/without leaving a partially rewritten file
 * (the store's rewrite is atomic). A cut that removes nothing does not touch
 * the file at all.
 */
export function rewindSession(store: SessionStore, turns: unknown): RewindSessionResult {
  const parsed = validateRewindTurns(turns);
  if (!parsed.ok) throw new SessionError(parsed.error);
  const events = store.loadStrict();
  const cut = computeRewindCut(events, parsed.turns);
  if (cut.removedCount === 0) return { cut, rewritten: false, path: store.path };
  // The kept prefix is an unchanged suffix-free copy of a dense log, so its
  // `seq` values stay dense and resume keeps working; nothing is renumbered.
  store.rewrite(events.slice(0, cut.cutIndex));
  return { cut, rewritten: true, path: store.path };
}
